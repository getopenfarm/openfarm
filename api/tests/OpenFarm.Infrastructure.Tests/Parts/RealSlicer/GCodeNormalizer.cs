using System.Text.RegularExpressions;

namespace OpenFarm.Infrastructure.Tests.Parts.RealSlicer;

internal sealed record GCodeDiffResult(bool IsMatch, string Message);

/// <summary>
/// Strips volatile G-code content (timestamps, generator version strings, embedded thumbnails,
/// absolute paths, the full internal-settings config dump) before comparing a real slice's output
/// against a golden fixture — an exact byte diff would fail on harmless slicer-version/GUI-vs-CLI
/// noise even when the actual toolpath is unchanged. The CONFIG_BLOCK comment dump in particular
/// echoes back every option OrcaSlicer's schema knows about, whose exact membership can differ
/// between a GUI export and a headless CLI invocation of the same version/settings without
/// indicating any real difference in what gets printed — it's dropped wholesale rather than
/// diffed key-by-key.
/// </summary>
internal static partial class GCodeNormalizer
{
    public static IReadOnlyList<string> Normalize(string gcode)
    {
        var withoutConfigBlock = ConfigBlockRegex().Replace(gcode, string.Empty);
        var withoutThumbnail = ThumbnailBlockRegex().Replace(withoutConfigBlock, string.Empty);

        return withoutThumbnail
            .Split('\n')
            .Select(line => line.TrimEnd('\r'))
            .Where(line => line.Length > 0 && !IsVolatileLine(line))
            .ToList();
    }

    public static GCodeDiffResult Diff(IReadOnlyList<string> expected, IReadOnlyList<string> actual)
    {
        var minLength = Math.Min(expected.Count, actual.Count);
        var mismatches = new List<string>();

        for (var i = 0; i < minLength && mismatches.Count < 20; i++)
        {
            if (expected[i] != actual[i])
            {
                mismatches.Add($"  line {i + 1}:\n    expected: {expected[i]}\n    actual:   {actual[i]}");
            }
        }

        if (expected.Count != actual.Count)
        {
            mismatches.Add($"  line count differs: expected {expected.Count} normalized lines, actual {actual.Count}.");
        }

        return new GCodeDiffResult(mismatches.Count == 0, string.Join("\n", mismatches));
    }

    private static bool IsVolatileLine(string line) =>
        GeneratedByRegex().IsMatch(line) || DateStampRegex().IsMatch(line) || AbsolutePathRegex().IsMatch(line);

    [GeneratedRegex(@";\s*thumbnail begin.*?;\s*thumbnail end", RegexOptions.Singleline | RegexOptions.IgnoreCase)]
    private static partial Regex ThumbnailBlockRegex();

    [GeneratedRegex(@";\s*CONFIG_BLOCK_START.*?;\s*CONFIG_BLOCK_END", RegexOptions.Singleline | RegexOptions.IgnoreCase)]
    private static partial Regex ConfigBlockRegex();

    [GeneratedRegex("generated by", RegexOptions.IgnoreCase)]
    private static partial Regex GeneratedByRegex();

    [GeneratedRegex(@"\d{4}-\d{2}-\d{2}|on \d.+ at \d")]
    private static partial Regex DateStampRegex();

    [GeneratedRegex(@"(/Users/|/home/|/var/folders/|/private/tmp/|[A-Za-z]:\\)")]
    private static partial Regex AbsolutePathRegex();
}
