    private const string Project = """{"printer_model":"Bambu Lab P1S","printer_settings_id":"Bambu Lab P1S 0.6 nozzle - Scrubbler","nozzle_diameter":["0.6"],"filament_type":["PETG","PLA"],"filament_colour":["#000000","#FFFFFF"],"filament_settings_id":["Custom PETG","Unused PLA"],"print_settings_id":"0.30mm Standard","curr_bed_type":"Textured PEI Plate","sparse_infill_density":"25%"}""";
    private const string SliceInfo = """<config><plate><metadata key="index" value="1"/><metadata key="printer_model_id" value="C12"/><metadata key="nozzle_diameters" value="0.6"/><metadata key="prediction" value="10790"/><metadata key="weight" value="176.84"/><filament id="1" type="PETG" color="#000000" used_g="176.84" used_for_object="true"/><filament id="2" type="PLA" used_g="0" used_for_object="false" used_for_support="false"/><nozzle nozzle_diameter="0.6"/></plate></config>""";

    [Fact]
    public async Task SlicedProject_PerPlateMetadataRecoversHeaderlessGCode_AndExcludesUnusedFilaments()
    {
        using var zip = Zip(("Metadata/project_settings.config", Project), ("Metadata/slice_info.config", SliceInfo),
            ("Metadata/plate_1.json", """{"nozzle_diameter":0.6000000238418579}"""), ("Metadata/plate_1.gcode", "; generated by OrcaSlicer 2.4.2 on 2026-09-29\nG28\nG1 X1"));
        var result = await new AlreadySlicedFileMetadataParser().ParseAsync(zip, PartFileFormat.ThreeMf, CancellationToken.None);
        result.NozzleDiameterMm.Should().Be(0.6m);
        result.EstimatedPrintTimeMinutes.Should().Be(179);
        result.EstimatedFilamentWeightGrams.Should().Be(176.84m);
        result.DetectedFilamentSlots.Should().ContainSingle(s => s.MaterialType == "PETG");
        result.MaterialMetadataComplete.Should().BeTrue();
        result.Estimation!.MachineModel.Should().Be("Bambu Lab P1S");
        result.Estimation.MachineProfileName.Should().Contain("Scrubbler");
        result.Estimation.Source.Should().Be("EmbeddedSlicedMetadata");
        result.Estimation.Engine.Should().Be("OrcaSlicer");
        result.Estimation.Version.Should().Be("2.4.2");
        result.Warnings.Should().BeEmpty();
    }

    [Fact]
    public async Task SlicedProject_ConflictsLeaveRequirementsAndIndividualMetricsUnknown()
    {
        using var zip = Zip(("Metadata/slice_info.config", SliceInfo), ("Metadata/plate_1.gcode",
            "; nozzle_diameter = 0.4\n; filament_type = ABS\n; total estimated time = 5m\n; filament used [g] = 2\nG28"));
        var result = await new AlreadySlicedFileMetadataParser().ParseAsync(zip, PartFileFormat.ThreeMf, CancellationToken.None);
        result.NozzleDiameterMm.Should().BeNull();
        result.MaterialMetadataComplete.Should().BeFalse();
        result.EstimatedPrintTimeMinutes.Should().BeNull();
        result.EstimatedFilamentWeightGrams.Should().BeNull();
        result.Warnings.Should().HaveCount(4);
    }

    [Fact]
    public async Task SlicedProject_ConflictingNozzlesWithinSliceMetadataRemainUnknown()
    {
        using var zip = Zip(("Metadata/slice_info.config", SliceInfo.Replace("value=\"0.6\"", "value=\"0.4;0.6\"", StringComparison.Ordinal)),
            ("Metadata/plate_1.gcode", "; nozzle_diameter = 0.6\nG28"));
        var result = await new AlreadySlicedFileMetadataParser().ParseAsync(zip, PartFileFormat.ThreeMf, CancellationToken.None);
        result.NozzleDiameterMm.Should().BeNull();
        result.Warnings.Should().Contain(w => w.Contains("nozzle", StringComparison.Ordinal));
    }

    [Fact]
    public async Task UnslicedProject_ExtractsMachineNozzleCustomProfilesAndMultipleMaterials()
    {
        using var zip = Zip(("Metadata/project_settings.config", Project), ("Metadata/model_settings.config", "<config><plate/><plate/></config>"));
        var result = await new UnslicedProjectMaterialResolver().ResolveAsync(zip, CancellationToken.None);
        result.HasEmbeddedSettings.Should().BeTrue();
        result.NozzleDiameterMm.Should().Be(0.6m);
        result.PlateCount.Should().Be(2);
        result.FilamentSlots.Should().HaveCount(2);
        result.Estimation!.MachineProfileName.Should().Contain("Scrubbler");
        result.EstimationUnavailableReason.Should().BeNull();
    }

    [Fact]
    public async Task UnslicedProject_KeepsOnlyTheFilamentsItsObjectsPrintWith()
    {
        // Slot 2 ("Unused PLA") is defined by the project but no object uses it.
        using var zip = Zip(("Metadata/project_settings.config", Project), ("Metadata/model_settings.config",
            "<config><object id=\"2\"><metadata key=\"extruder\" value=\"1\"/><part id=\"1\" subtype=\"normal_part\"/></object>"
            + "<plate><model_instance><metadata key=\"object_id\" value=\"2\"/></model_instance></plate></config>"),
            ("3D/Objects/a.model", "<model><mesh/></model>"));
        var result = await new UnslicedProjectMaterialResolver().ResolveAsync(zip, CancellationToken.None);
        result.FilamentSlots.Should().ContainSingle().Which.MaterialType.Should().Be("PETG");
        result.MaterialType.Should().Be("PETG");
        result.Estimation!.FilamentProfileNames.Should().Equal("Custom PETG");
    }

