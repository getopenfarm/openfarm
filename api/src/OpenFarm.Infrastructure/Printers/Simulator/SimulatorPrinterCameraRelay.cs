using System.Runtime.CompilerServices;
using OpenFarm.Application.Printers;

namespace OpenFarm.Infrastructure.Printers.Simulator;

/// <summary>
/// Built-in <see cref="IPrinterCameraRelay"/> for simulated printers — periodically yields a small
/// generated placeholder JPEG so the camera panel renders a live-looking image instead of its
/// "unavailable" state (FR-006/US3). Mirrors <c>BambuCameraRelay</c>'s long-lived-stream shape: stays
/// alive, yielding frames, until <paramref name="cancellationToken"/> is cancelled.
/// </summary>
public sealed class SimulatorPrinterCameraRelay : IPrinterCameraRelay
{
    private static readonly TimeSpan FrameInterval = TimeSpan.FromSeconds(1);

    // Smallest possible valid JPEG (a 1x1 white pixel) — enough to satisfy "produces a camera image"
    // without a real imaging dependency (plan.md's Technical Context).
    private static readonly byte[] PlaceholderFrame =
    [
        0xFF, 0xD8, 0xFF, 0xE0, 0x00, 0x10, 0x4A, 0x46, 0x49, 0x46, 0x00, 0x01, 0x01, 0x00, 0x00, 0x01,
        0x00, 0x01, 0x00, 0x00, 0xFF, 0xDB, 0x00, 0x43, 0x00, 0x03, 0x02, 0x02, 0x02, 0x02, 0x02, 0x03,
        0x02, 0x02, 0x02, 0x03, 0x03, 0x03, 0x03, 0x04, 0x06, 0x04, 0x04, 0x04, 0x04, 0x04, 0x08, 0x06,
        0x06, 0x05, 0x06, 0x09, 0x08, 0x0A, 0x0A, 0x09, 0x08, 0x09, 0x09, 0x0A, 0x0C, 0x0F, 0x0C, 0x0A,
        0x0B, 0x0E, 0x0B, 0x09, 0x09, 0x0D, 0x11, 0x0D, 0x0E, 0x0F, 0x10, 0x10, 0x11, 0x10, 0x0A, 0x0C,
        0x12, 0x13, 0x12, 0x10, 0x13, 0x0F, 0x10, 0x10, 0x10, 0xFF, 0xC9, 0x00, 0x0B, 0x08, 0x00, 0x01,
        0x00, 0x01, 0x01, 0x01, 0x11, 0x00, 0xFF, 0xCC, 0x00, 0x06, 0x00, 0x10, 0x10, 0x05, 0xFF, 0xDA,
        0x00, 0x08, 0x01, 0x01, 0x00, 0x00, 0x3F, 0x00, 0xD2, 0xCF, 0x20, 0xFF, 0xD9,
    ];

    public async IAsyncEnumerable<byte[]> StreamFramesAsync(
        PrinterConnectionDetails details,
        [EnumeratorCancellation] CancellationToken cancellationToken)
    {
        using var timer = new PeriodicTimer(FrameInterval);
        yield return PlaceholderFrame;

        while (await timer.WaitForNextTickAsync(cancellationToken))
        {
            yield return PlaceholderFrame;
        }
    }
}
