"""Derive browser query guards from endpoint authorization metadata after Orval generation."""
from pathlib import Path
import json
import re

root = Path(__file__).resolve().parent.parent
rules = []
for source in sorted((root / 'api/src/OpenFarm.Api/Endpoints').rglob('*.cs')):
    text = source.read_text(encoding='utf-8-sig')
    endpoints = list(re.finditer(r'\[Permission\(([^\]]+)\)\]\s*public sealed class (\w+)', text))
    for index, endpoint in enumerate(endpoints):
        body = text[endpoint.end():endpoints[index + 1].start() if index + 1 < len(endpoints) else len(text)]
        permissions = re.findall(r'"([^"]+)"', endpoint[1])
        permissions = [key for key in permissions if not key.startswith('auth:')]
        for path in re.findall(r'\bGet\("([^"]+)"\)', body):
            pattern = '^' + re.sub(r'\{[^}]+\}', '[^/]+', re.escape(path).replace(r'\{', '{').replace(r'\}', '}')) + '$'
            rules.append({'pattern': pattern, 'permissions': permissions})
rules.sort(key=lambda rule: (rule['pattern'].count('[^/]+'), -len(rule['pattern'])))
output = root / 'web/src/lib/auth/apiPermissions.generated.ts'
output.write_text('// Generated by tools/generate-query-permissions.py. Do not edit.\nexport const apiQueryPermissions = ' + json.dumps(rules, indent=2) + ';\n')
for source in (root / 'web/src/lib/api/generated').rglob('*.ts'):
    text = source.read_text()
    def rewrite(match):
        names = [name.strip() for name in match[1].split(',') if name.strip()]
        if 'useQuery' not in names:
            return match[0]
        names.remove('useQuery')
        original = "import { " + ', '.join(names) + " } from '@tanstack/react-query';\n" if names else ''
        return original + "import { useAuthorizedQuery as useQuery } from '@/lib/auth/useAuthorizedQuery';"
    text = re.sub(r"import \{([^}]+)\} from '@tanstack/react-query';", rewrite, text)
    source.write_text(text)
